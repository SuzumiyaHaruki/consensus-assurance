// This file is generated by the audit harness. It never changes production
// logic; it feeds message shapes through the real Step entry points and
// reports what the state machines did, including recovered panics.

func assuranceEmit(t *testing.T, event map[string]any) {
	t.Helper()
	raw, err := json.Marshal(event)
	if err != nil {
		t.Fatalf("marshal CA_EVENT: %v", err)
	}
	fmt.Println("CA_EVENT " + string(raw))
}

// assuranceCluster builds three real raft instances for the voter set
// {1,2,3}, wires them through the standard test network and elects node 1 as
// leader with a committed entry in its term, so a leader reaches
// sendMsgReadIndexResponse directly instead of queueing read requests.
func assuranceCluster(t *testing.T) (leader, follower2, follower3 *raft) {
	t.Helper()
	r1 := newTestRaft(1, 10, 1, newTestMemoryStorage(withPeers(1, 2, 3)))
	r2 := newTestRaft(2, 10, 1, newTestMemoryStorage(withPeers(1, 2, 3)))
	r3 := newTestRaft(3, 10, 1, newTestMemoryStorage(withPeers(1, 2, 3)))
	nt := newNetwork(r1, r2, r3)
	nt.send(pb.Message{From: 1, To: 1, Type: pb.MsgHup})
	if r1.state != StateLeader {
		t.Fatalf("node 1 is %v, want %v", r1.state, StateLeader)
	}
	if !r1.committedEntryInCurrentTerm() {
		t.Fatalf("leader 1 has no committed entry in term %d", r1.Term)
	}
	for _, r := range []*raft{r1, r2, r3} {
		r.readMessages()
	}
	return r1, r2, r3
}

type assuranceStepResult struct {
	panicked  bool
	recovered string
	msgs      []pb.Message
}

// assuranceStepRecover steps one message and recovers a panic, reporting the
// recovered value verbatim. Production code never recovers here: the recovered
// value is what would otherwise abort the caller's raft loop.
func assuranceStepRecover(r *raft, m pb.Message) (res assuranceStepResult) {
	defer func() {
		if v := recover(); v != nil {
			res.panicked = true
			res.recovered = fmt.Sprint(v)
		}
	}()
	_ = r.Step(m)
	res.msgs = r.readMessages()
	return res
}

func TestAssuranceReadIndexEmptyEntries(t *testing.T) {
	probe := func(probeID, role string, entries int, emptyProp, stepOnLeader, expectPanic bool) {
		leader, f2, f3 := assuranceCluster(t)
		_ = f3
		target, node := leader, "1"
		if !stepOnLeader {
			target, node = f2, "2"
		}
		assuranceEmit(t, map[string]any{
			"event":        "probe_setup",
			"probe_id":     probeID,
			"role":         role,
			"node":         node,
			"leader":       "1",
			"term":         target.Term,
			"leader_state": leader.state.String(),
			"voters":       leader.trk.ConfState().Voters,
		})

		var payload []pb.Entry
		for i := 0; i < entries; i++ {
			payload = append(payload, pb.Entry{Data: []byte(fmt.Sprintf("assurance-rctx-%s-%d", probeID, i))})
		}
		msgType := pb.MsgReadIndex
		if emptyProp {
			msgType = pb.MsgProp
		}
		m := pb.Message{From: target.id, To: target.id, Type: msgType, Entries: payload}
		stepEvent := "read_index_step"
		outcomeEvent := "read_index_step_outcome"
		if emptyProp {
			stepEvent, outcomeEvent = "prop_step", "prop_step_outcome"
		}
		assuranceEmit(t, map[string]any{
			"event":         stepEvent,
			"probe_id":      probeID,
			"role":          role,
			"entries":       entries,
			"message_type":  msgType.String(),
			"node":          node,
			"leader":        "1",
			"term":          target.Term,
			"log_committed": leader.raftLog.committed,
			"log_applied":   leader.raftLog.applied,
		})
		res := assuranceStepRecover(target, m)
		emitted := map[string]int{}
		for _, out := range res.msgs {
			emitted[out.Type.String()]++
		}
		assuranceEmit(t, map[string]any{
			"event":               outcomeEvent,
			"probe_id":            probeID,
			"role":                role,
			"entries":             entries,
			"message_type":        msgType.String(),
			"node":                node,
			"panicked":            res.panicked,
			"recovered":           res.recovered,
			"messages_emitted":    len(res.msgs),
			"emitted_by_type":     emitted,
			"state_after_step":    target.state.String(),
			"term_after_step":     target.Term,
			"pending_after_step":  len(target.readOnly.pendingReadIndex),
			"queue_after_step":    len(target.readOnly.readIndexQueue),
			"committed_after_step": target.raftLog.committed,
		})
		assuranceEmit(t, map[string]any{
			"event":        "probe_done",
			"probe_id":     probeID,
			"role":         role,
			"entries":      entries,
			"panicked":     res.panicked,
			"message_type": msgType.String(),
		})
		// Harness expectation: a change in these observed behaviours must make
		// this test fail rather than silently reshape the evidence.
		if res.panicked != expectPanic {
			t.Fatalf("probe %s: panicked=%v, want %v (recovered %q)", probeID, res.panicked, expectPanic, res.recovered)
		}
		if role == "follower" && (len(res.msgs) != 1 || res.msgs[0].Type != pb.MsgReadIndex || res.msgs[0].To != 1) {
			t.Fatalf("probe %s: follower emitted %+v, want one forwarded MsgReadIndex to the leader", probeID, res.msgs)
		}
	}

	// Probes on the leader: the message shapes a peer could deliver, plus the
	// well-formed request index as a positive control and the empty proposal
	// whose deliberate guard is documented in the captured source.
	probe("leader/empty-entries", "leader", 0, false, true, true)
	probe("leader/one-entry", "leader", 1, false, true, false)
	probe("leader/empty-prop", "leader", 0, true, true, true)
	// Probes on a follower: the forwarding hop for the same shapes.
	probe("follower/empty-entries", "follower", 0, false, false, false)
	probe("follower/one-entry", "follower", 1, false, false, false)
}
