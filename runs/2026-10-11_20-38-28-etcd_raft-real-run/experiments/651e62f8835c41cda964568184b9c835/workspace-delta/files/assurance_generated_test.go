// This file is generated by the audit harness. It never changes production
// logic; it drives the real state machine through its normal entry points
// (Step / ReadIndex forwarding) and reports observations as CA_EVENT lines.

func assuranceEmit(t *testing.T, event map[string]any) {
	t.Helper()
	raw, err := json.Marshal(event)
	if err != nil {
		t.Fatalf("marshal CA_EVENT: %v", err)
	}
	fmt.Println("CA_EVENT " + string(raw))
}

// assuranceCluster builds three real raft instances for the voter set
// {1,2,3}, wires them through the standard test network and elects node 1 as
// leader with a committed entry in its term, which is the precondition for
// the leader to answer MsgReadIndex immediately (see stepLeader /
// committedEntryInCurrentTerm).
func assuranceCluster(t *testing.T) (leader, follower2, follower3 *raft) {
	t.Helper()
	r1 := newTestRaft(1, 10, 1, newTestMemoryStorage(withPeers(1, 2, 3)))
	r2 := newTestRaft(2, 10, 1, newTestMemoryStorage(withPeers(1, 2, 3)))
	r3 := newTestRaft(3, 10, 1, newTestMemoryStorage(withPeers(1, 2, 3)))
	nt := newNetwork(r1, r2, r3)
	nt.send(pb.Message{From: 1, To: 1, Type: pb.MsgHup})
	if r1.state != StateLeader {
		t.Fatalf("node 1 is %v, want %v", r1.state, StateLeader)
	}
	if !r1.committedEntryInCurrentTerm() {
		t.Fatalf("leader 1 has no committed entry in term %d, read index would be queued instead of served", r1.Term)
	}
	assuranceEmit(t, map[string]any{
		"event":                   "leader_elected",
		"leader":                  "1",
		"term":                    r1.Term,
		"committed":               r1.raftLog.committed,
		"committed_in_term":       r1.committedEntryInCurrentTerm(),
		"read_only_option":        "ReadOnlySafe",
		"leader_state":            r1.state.String(),
		"voters":                  r1.trk.ConfState().Voters,
		"follower2_lead":          r2.lead,
		"follower3_lead":          r3.lead,
	})
	// Start every scenario from a quiescent message queue.
	for _, r := range []*raft{r1, r2, r3} {
		r.readMessages()
	}
	return r1, r2, r3
}

// assuranceForward makes follower r issue a real local ReadIndex for ctx and
// returns the MsgReadIndex that r forwards to its leader (this is exactly what
// RawNode.ReadIndex/Node.ReadIndex do: Step a local MsgReadIndex, which
// stepFollower forwards to r.lead without a term).
func assuranceForward(t *testing.T, r *raft, ctx []byte) pb.Message {
	t.Helper()
	if err := r.Step(pb.Message{
		From:    r.id,
		To:      r.id,
		Type:    pb.MsgReadIndex,
		Entries: []pb.Entry{{Data: ctx}},
	}); err != nil {
		t.Fatalf("node %d step MsgReadIndex: %v", r.id, err)
	}
	msgs := r.readMessages()
	if len(msgs) != 1 {
		t.Fatalf("node %d forwarded %d messages, want exactly 1", r.id, len(msgs))
	}
	m := msgs[0]
	if m.Type != pb.MsgReadIndex || m.To != r.lead || len(m.Entries) != 1 || string(m.Entries[0].Data) != string(ctx) {
		t.Fatalf("node %d forwarded %+v, want MsgReadIndex to %d carrying %q", r.id, m, r.lead, ctx)
	}
	return m
}

// assurancePump delivers messages to the node each one addresses, using the
// real Step path of every state machine, and counts the read index responses
// that reach a requester. It returns the messages left undelivered when the
// per-round budget runs out.
func assurancePump(t *testing.T, nodes map[uint64]*raft, pending []pb.Message, responses map[uint64]int, budget int) []pb.Message {
	t.Helper()
	for len(pending) > 0 && budget > 0 {
		budget--
		m := pending[0]
		pending = pending[1:]
		target, ok := nodes[m.To]
		if !ok {
			t.Fatalf("message %s addressed to unknown node %d", m.Type, m.To)
		}
		if m.Type == pb.MsgReadIndexResp {
			responses[m.To]++
		}
		if err := target.Step(m); err != nil {
			t.Fatalf("node %d step %s: %v", m.To, m.Type, err)
		}
		pending = append(pending, target.readMessages()...)
	}
	return pending
}

func assuranceCountReadStates(nodes map[uint64]*raft) map[string]int {
	out := map[string]int{}
	for id, r := range nodes {
		out[fmt.Sprintf("%d", id)] = len(r.readStates)
	}
	return out
}

func TestAssuranceReadIndexRepeatedRctx(t *testing.T) {
	// admit forwards one ReadIndex from follower f, delivers the leader's
	// heartbeat broadcast to the addressed followers (so that a real
	// MsgHeartbeatResp carrying the rctx is produced by their state machines)
	// and holds those acknowledgments back. It returns the leader's outgoing
	// messages for inspection.
	admit := func(lead *raft, nodes map[uint64]*raft, f *raft, ctx []byte, held *[]pb.Message) []pb.Message {
		t.Helper()
		lead.Step(assuranceForward(t, f, ctx))
		msgs := lead.readMessages()
		for _, m := range msgs {
			target, ok := nodes[m.To]
			if !ok {
				t.Fatalf("leader sent %s to unknown node %d", m.Type, m.To)
			}
			if err := target.Step(m); err != nil {
				t.Fatalf("node %d step %s: %v", m.To, m.Type, err)
			}
			*held = append(*held, target.readMessages()...)
		}
		return msgs
	}
	requestEvent := func(scenario, requestID, requester string, ctx []byte, lead *raft) {
		assuranceEmit(t, map[string]any{
			"event":         "read_index_request",
			"request_id":    requestID,
			"requester":     requester,
			"rctx":          string(ctx),
			"scenario":      scenario,
			"pending_after": len(lead.readOnly.pendingReadIndex),
			"queue_after":   len(lead.readOnly.readIndexQueue),
			"leader_state":  lead.state.String(),
		})
	}

	// Scenario "duplicate_ctx": two different voters each issue one ReadIndex
	// carrying the *same* rctx, with no quorum acknowledgment in between.
	dupCtx := []byte("assurance-dup-rctx")
	leader, f2, f3 := assuranceCluster(t)
	nodes := map[uint64]*raft{1: leader, 2: f2, 3: f3}
	responses := map[uint64]int{}
	var held []pb.Message

	// Requester 2 reaches the leader first and is admitted.
	admit(leader, nodes, f2, dupCtx, &held)
	requestEvent("duplicate_ctx", "duplicate/2", "2", dupCtx, leader)

	// Requester 3 reaches the same leader with an equal rctx while requester
	// 2's status is still pending.
	admit(leader, nodes, f3, dupCtx, &held)
	requestEvent("duplicate_ctx", "duplicate/3", "3", dupCtx, leader)

	// Retrying the same rctx is likewise accepted by the leader without
	// creating a new pending status.
	queueBefore := len(leader.readOnly.readIndexQueue)
	retryMsgs := admit(leader, nodes, f3, dupCtx, &held)
	assuranceEmit(t, map[string]any{
		"event":              "read_index_retry",
		"request_id":         "duplicate/3",
		"requester":          "3",
		"rctx":               string(dupCtx),
		"scenario":           "duplicate_ctx",
		"queue_before":       queueBefore,
		"queue_after":        len(leader.readOnly.readIndexQueue),
		"pending_after":      len(leader.readOnly.pendingReadIndex),
		"heartbeats_emitted": len(retryMsgs),
		"leader_state":       leader.state.String(),
	})

	// Observation window: the held acknowledgments and the leader's own
	// periodic heartbeats keep flowing. Every message is processed by the
	// state machine it addresses, which is the leader's normal opportunity to
	// complete pending read requests.
	const rounds = 8
	pending := held
	for i := 0; i < rounds; i++ {
		leader.tickHeartbeat()
		pending = append(pending, leader.readMessages()...)
		pending = assurancePump(t, nodes, pending, responses, 200)
		assuranceEmit(t, map[string]any{
			"event":          "read_index_round",
			"scenario":       "duplicate_ctx",
			"round":          i,
			"leader_state":   leader.state.String(),
			"term":           leader.Term,
			"pending":        len(leader.readOnly.pendingReadIndex),
			"queue":          len(leader.readOnly.readIndexQueue),
			"responses_to_2": responses[2],
			"responses_to_3": responses[3],
			"read_states":    assuranceCountReadStates(nodes),
			"undelivered":    len(pending),
		})
	}

	assuranceEmit(t, map[string]any{
		"event":         "read_index_delivery",
		"request_id":    "duplicate/2",
		"requester":     "2",
		"rctx":          string(dupCtx),
		"scenario":      "duplicate_ctx",
		"responded":     responses[2] > 0,
		"responses":     responses[2],
		"rounds_waited": rounds,
		"leader_state":  leader.state.String(),
	})
	assuranceEmit(t, map[string]any{
		"event":                 "read_index_delivery",
		"request_id":            "duplicate/3",
		"requester":             "3",
		"rctx":                  string(dupCtx),
		"scenario":              "duplicate_ctx",
		"responded":             responses[3] > 0,
		"responses":             responses[3],
		"rounds_waited":         rounds,
		"leader_state":          leader.state.String(),
		"requester_read_states": len(f3.readStates),
	})
	if responses[2] == 0 {
		t.Fatalf("harness check: first requester got no read index response")
	}
	if responses[3] != 0 || len(f3.readStates) != 0 {
		t.Fatalf("expected the second requester to be starved, got %d responses and %d read states",
			responses[3], len(f3.readStates))
	}

	// Scenario "distinct_ctx" (control): the same two requesters, same order,
	// same timing, but distinct rctxes.
	leaderC, c2, c3 := assuranceCluster(t)
	cnodes := map[uint64]*raft{1: leaderC, 2: c2, 3: c3}
	cresponses := map[uint64]int{}
	var cheld []pb.Message
	ctx2 := []byte("assurance-ctl-rctx-2")
	ctx3 := []byte("assurance-ctl-rctx-3")
	admit(leaderC, cnodes, c2, ctx2, &cheld)
	requestEvent("distinct_ctx", "control/2", "2", ctx2, leaderC)
	admit(leaderC, cnodes, c3, ctx3, &cheld)
	requestEvent("distinct_ctx", "control/3", "3", ctx3, leaderC)
	cpending := cheld
	for i := 0; i < rounds; i++ {
		leaderC.tickHeartbeat()
		cpending = append(cpending, leaderC.readMessages()...)
		cpending = assurancePump(t, cnodes, cpending, cresponses, 200)
	}
	assuranceEmit(t, map[string]any{
		"event":        "read_index_delivery",
		"request_id":   "control/2",
		"requester":    "2",
		"rctx":         string(ctx2),
		"scenario":     "distinct_ctx",
		"responded":    cresponses[2] > 0,
		"responses":    cresponses[2],
		"leader_state": leaderC.state.String(),
	})
	assuranceEmit(t, map[string]any{
		"event":        "read_index_delivery",
		"request_id":   "control/3",
		"requester":    "3",
		"rctx":         string(ctx3),
		"scenario":     "distinct_ctx",
		"responded":    cresponses[3] > 0,
		"responses":    cresponses[3],
		"leader_state": leaderC.state.String(),
	})
	if cresponses[2] == 0 || cresponses[3] == 0 {
		t.Fatalf("control failure: distinct rctxes answered %v", cresponses)
	}

	// Scenario "same_requester_retry": one requester retries its own rctx while
	// the first status is pending. The retry is equally deduplicated, but the
	// single response is addressed to that same requester.
	leaderS, s2, s3 := assuranceCluster(t)
	snodes := map[uint64]*raft{1: leaderS, 2: s2, 3: s3}
	sresponses := map[uint64]int{}
	var sheld []pb.Message
	ownCtx := []byte("assurance-own-rctx")
	admit(leaderS, snodes, s2, ownCtx, &sheld)
	requestEvent("same_requester_retry", "retry/2", "2", ownCtx, leaderS)
	admit(leaderS, snodes, s2, ownCtx, &sheld)
	spending := sheld
	for i := 0; i < rounds; i++ {
		leaderS.tickHeartbeat()
		spending = append(spending, leaderS.readMessages()...)
		spending = assurancePump(t, snodes, spending, sresponses, 200)
	}
	assuranceEmit(t, map[string]any{
		"event":        "read_index_delivery",
		"request_id":   "retry/2",
		"requester":    "2",
		"rctx":         string(ownCtx),
		"scenario":     "same_requester_retry",
		"responded":    sresponses[2] > 0,
		"responses":    sresponses[2],
		"leader_state": leaderS.state.String(),
	})
	if sresponses[2] == 0 {
		t.Fatalf("harness check: retrying requester was not answered")
	}
}
