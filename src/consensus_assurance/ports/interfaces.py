from typing import Protocol


class ExecutionBackend(Protocol):
    name: str
    version: str
    harness_kind: str
    harness_filename: str
    harness_instructions: str
    def environment(self, workspace) -> dict[str, str]: ...
    def read_only_roots(self) -> list: ...
    def parse_test_result(self, check, text): ...
    def resolve_harness(self, harness, source, target_files) -> str: ...
    def experiment_command(self, execution_package=None, harness_filename=None) -> list[str]: ...
    def version_command(self) -> list[str]: ...


class AgentBackend(Protocol):
    name: str
    mock: bool
    def probe(self, runner): ...
    def investigate(self, runner, prompt, directory, snapshot_id, timeout, session_id=None): ...


class PreparedExecutionBackend(ExecutionBackend, Protocol):
    """Optional run-local preparation; ordinary Go/Python execution is unchanged."""
    def prepare_run(self, runner, snapshot_id, timeout, mode): ...
    def validate_builds(self, root, snapshot_id, deadline=None): ...
    def execute(self, runner, command, workspace, snapshot_id, timeout, mode, action): ...
